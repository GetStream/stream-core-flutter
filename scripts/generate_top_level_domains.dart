/// Top-Level Domain Generator
///
/// Generates the set of top-level domains that `findLinks` and `findLinkAt` in
/// `stream_core` accept for an address written without a scheme, such as
/// `example.com`.
///
/// Source: the IANA root zone list,
/// https://data.iana.org/TLD/tlds-alpha-by-domain.txt
///
/// Output: `packages/stream_core/lib/src/utils/link_finder.tlds.g.dart`, a
/// part of `link_finder.dart` holding a private `const` set with one lowercase
/// domain per line. An internationalized domain
/// is listed in both its ASCII form (`xn--p1ai`) and its Unicode form (`рф`),
/// each commented with the other.
///
/// Usage (from anywhere in the monorepo):
///   melos run generate:tlds
///
/// Or directly, from the repository root:
///   dart run scripts/generate_top_level_domains.dart
///
/// The `update_top_level_domains` workflow runs it monthly and opens a pull
/// request when the list has changed. Run it by hand to pick up a domain
/// sooner. It needs network access, so it is not part of `generate:all`.
///
/// Steps:
///   1. Downloads the list and checks that it starts with its version line
///      and that every entry is an ASCII domain.
///   2. Decodes each `xn--` domain from punycode (RFC 3492).
///   3. Sorts the domains and renders the set.
///   4. Writes the file with the list's version in its header, or leaves it
///      as it is when the set has not changed, so a new list version alone
///      does not produce a diff.
///
/// Throws, writing nothing, if the download fails or the list is not in the
/// expected format.
library;

import 'dart:convert';
import 'dart:io';

const _kSource = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const _kOutput = 'packages/stream_core/lib/src/utils/link_finder.tlds.g.dart';
const _kVersionPrefix = '# Version ';
const _kPunycodePrefix = 'xn--';

final _asciiDomain = RegExp(r'^[a-z0-9-]+$');

Future<void> main() async {
  final lines = await _download(Uri.parse(_kSource));
  if (lines.isEmpty || !lines.first.startsWith(_kVersionPrefix)) {
    throw FormatException('Expected the list to start with its version', lines.firstOrNull);
  }

  final domains = [
    for (final line in lines.skip(1))
      if (line.trim().isNotEmpty) _validated(line.trim().toLowerCase()),
  ];
  final entries = [for (final domain in domains) ..._entriesFor(domain)]..sort((a, b) => a.domain.compareTo(b.domain));

  final file = File('${File.fromUri(Platform.script).parent.parent.path}/$_kOutput');
  final set = _renderSet(entries);
  if (file.existsSync() && file.readAsStringSync().endsWith(set)) {
    stdout.writeln('$_kOutput already has the ${domains.length} top-level domains');
    return;
  }

  file
    ..createSync(recursive: true)
    ..writeAsStringSync(_renderHeader(lines.first.substring(2)) + set);
  stdout.writeln('Wrote ${domains.length} top-level domains to $_kOutput');
}

// A domain in the set, and its other form when it is internationalized.
typedef _Entry = ({String domain, String? otherForm});

// The [domain] from the list, or a [FormatException] when it is not an ASCII
// domain, as when the download returns something other than the list.
String _validated(String domain) {
  if (!_asciiDomain.hasMatch(domain)) throw FormatException('Expected an ASCII domain', domain);
  return domain;
}

// The entries for a domain from the list: one for an ASCII domain, and one
// per form for an internationalized one.
List<_Entry> _entriesFor(String ascii) {
  if (!ascii.startsWith(_kPunycodePrefix)) return [(domain: ascii, otherForm: null)];

  final unicode = _decodePunycode(ascii.substring(_kPunycodePrefix.length));
  return [(domain: ascii, otherForm: unicode), (domain: unicode, otherForm: ascii)];
}

Future<List<String>> _download(Uri uri) async {
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(uri)).close();
    if (response.statusCode != HttpStatus.ok) {
      throw HttpException('GET $uri failed with ${response.statusCode}', uri: uri);
    }

    return const LineSplitter().convert(await response.transform(utf8.decoder).join());
  } finally {
    client.close();
  }
}

// The header naming the source and the list version the set was built from.
String _renderHeader(String version) {
  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('//')
    ..writeln('// Generated by `melos run generate:tlds` from')
    ..writeln('// $_kSource')
    ..writeln('// $version')
    ..writeln()
    ..writeln("part of 'link_finder.dart';")
    ..writeln();
  return buffer.toString();
}

// The set itself, compared with the existing file to skip a no-op write.
String _renderSet(List<_Entry> entries) {
  final buffer = StringBuffer()
    ..writeln('// The top-level domains in the IANA root zone, lowercase.')
    ..writeln('//')
    ..writeln('// Internationalized domains are in both their ASCII and Unicode forms, each')
    ..writeln('// commented with the other.')
    ..writeln('const _kIanaTopLevelDomains = <String>{');

  for (final (:domain, :otherForm) in entries) {
    final comment = otherForm == null ? '' : ' // $otherForm';
    buffer.writeln("  '$domain',$comment");
  }

  buffer.writeln('};');
  return buffer.toString();
}

// RFC 3492 punycode decoding.
String _decodePunycode(String input) {
  const base = 36;
  const tMin = 1;
  const tMax = 26;
  const skew = 38;
  const damp = 700;
  const initialBias = 72;
  const initialN = 128;

  int adapt(int delta, int numPoints, {required bool firstTime}) {
    var scaled = firstTime ? delta ~/ damp : delta ~/ 2;
    scaled += scaled ~/ numPoints;
    var k = 0;
    while (scaled > ((base - tMin) * tMax) ~/ 2) {
      scaled ~/= base - tMin;
      k += base;
    }
    return k + (base - tMin + 1) * scaled ~/ (scaled + skew);
  }

  int digitValue(int codeUnit) {
    if (codeUnit >= 0x30 && codeUnit <= 0x39) return codeUnit - 0x30 + 26;
    if (codeUnit >= 0x61 && codeUnit <= 0x7A) return codeUnit - 0x61;
    if (codeUnit >= 0x41 && codeUnit <= 0x5A) return codeUnit - 0x41;
    throw FormatException('Invalid punycode digit', input);
  }

  // The code points before the last `-` are copied as they are. With no `-`,
  // every character is an encoded digit.
  final delimiter = input.lastIndexOf('-');
  final output = <int>[if (delimiter >= 0) ...input.substring(0, delimiter).codeUnits];

  var n = initialN;
  var i = 0;
  var bias = initialBias;
  var position = delimiter + 1;

  while (position < input.length) {
    final oldI = i;
    var weight = 1;
    for (var k = base; ; k += base) {
      if (position >= input.length) throw FormatException('Truncated punycode', input);
      final digit = digitValue(input.codeUnitAt(position++));
      i += digit * weight;
      final t = k <= bias ? tMin : (k >= bias + tMax ? tMax : k - bias);
      if (digit < t) break;
      weight *= base - t;
    }

    bias = adapt(i - oldI, output.length + 1, firstTime: oldI == 0);
    n += i ~/ (output.length + 1);
    i %= output.length + 1;
    output.insert(i++, n);
  }

  return String.fromCharCodes(output);
}
